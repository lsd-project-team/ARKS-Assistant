def rounded(text):
    return re.sub(r'(?<![\w.])−?\d+\.\d{4,}',lambda m:format(float(m[0].replace('−','-')),'.3f').replace('-','−'),text)

def reuse(number,bridge,stage='算目标',part=1,diagram=None):
    p=deepcopy(prior.PAGES[number-1]);p['old']=f'{number:02d}'
    for key in ['lead','explain','detail','remember']:p[key]=rounded(p[key])
    p.update(part=part,stage=stage,main=False,bridge=bridge,extra=None)
    if diagram:p['diagram']=diagram
    PAGES.append(p)

