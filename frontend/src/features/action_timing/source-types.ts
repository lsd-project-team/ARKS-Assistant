export type SourceEvidence = { path: string; line: number; version: string; code: string };
export type SourceValue = number | boolean | string | null | { [key: string]: SourceValue };
export type SourceStage = SourceEvidence & {
  kind: 'delay' | 'motion' | 'wait' | 'call' | 'unresolved' | 'loop' | 'background' | 'timeout';
  label: string;
  conditions: string[];
  background: boolean;
  method: string;
  expression?: string;
  milliseconds?: number | null;
  repeat?: boolean;
  note?: string;
  arguments?: string[];
  argument_values?: SourceValue[];
  motion_model?: {
    kind?: string;
    source_fixed_wait_ms?: number;
    duration_ms?: number | null;
    start_position?: number | null;
    acceleration?: number | null;
    deceleration?: number | null;
    jerk?: number | null;
    time_unit?: string;
    completion?: string;
    formula: string;
    conditions: string;
    distance?: number | null;
    target?: number | string | null;
    velocity?: number | null;
    velocity_expression: string;
    acceleration_expression: string;
    deceleration_expression: string;
    unresolved: string[];
  };
  definitions?: SourceEvidence[];
  iterations?: number | null;
};
export type SourceParameter = SourceEvidence & {
  name: string;
  value: SourceValue;
  expression: string;
};
export type SourceComponent = {
  milliseconds: number;
  factors: string[];
  conditions: string[];
  sources: (SourceEvidence & { milliseconds?: number; fixed_repetitions?: number })[];
  scope: 'conditional' | 'background' | 'expanded';
  note: string;
};
export type MissingRequirement = {
  category: string;
  required: string[];
  background: boolean;
  path: string;
  line: number;
  method: string;
};
export type SourceAction = {
  id: string;
  name: string;
  class_name: string;
  method: string;
  kind: 'node' | 'controller' | 'workflow' | 'placeholder';
  primary?: boolean;
  category?: string;
  analysis_unit?: 'method' | 'single_cycle' | 'wizard_step' | 'callback';
  known_components?: SourceComponent[];
  source_components?: SourceComponent[];
  missing_requirements?: MissingRequirement[];
  missing_categories?: string[];
  group: string;
  branch: string;
  entry: SourceEvidence;
  known_delay_min_ms: number | null;
  known_delay_max_ms: number | null;
  total_ms: number | null;
  complete: boolean;
  truncated: boolean;
  formula: string;
  motion_count: number;
  wait_count: number;
  timeout_count: number;
  execution_status?: 'complete' | 'partial' | 'skipped' | 'unavailable';
  status_reason?: string;
  stage_count?: number;
  parameter_count?: number;
  stages?: SourceStage[];
  per_item_timing?: { element_type: string; min_ms: number; max_ms: number | null }[];
  parameters?: SourceParameter[];
};
export type SourceTimingReport = {
  source_revision: string;
  source_files: number;
  mode: 'DryCycle';
  basis: 'source_defaults';
  scope: string;
  assumptions: string[];
  notes: string[];
  rows: SourceAction[];
};
